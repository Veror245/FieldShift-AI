import type { FieldPolygon } from "@/types/geojson"
import type { GeocodedAddress } from "@/utils/reverseGeocode"
import { formatCoordinates } from "@/utils/reverseGeocode"

type FieldLocationArgs = {
  farmName?: string
  polygon?: FieldPolygon | null
  hectares?: number
  coordinates?: { lat: number; lng: number } | null
  address?: GeocodedAddress | null
}

export function buildFieldLocationJson(args: FieldLocationArgs): string {
  const { farmName, polygon, hectares, coordinates, address } = args
  const payload = {
    farm_name: farmName ?? null,
    field: {
      coordinates: coordinates ?? null,
      hectares: hectares ?? null,
      polygon: polygon?.geometry ?? null,
    },
    address: address
      ? {
          formatted: address.formatted,
          village: address.village ?? null,
          city: address.city ?? null,
          district: address.district ?? null,
          state: address.state ?? null,
          country: address.country ?? null,
        }
      : null,
    generated_at: new Date().toISOString(),
  }
  return JSON.stringify(payload, null, 2)
}

export function exportFieldPdf(args: FieldLocationArgs): boolean {
  const { farmName, polygon, hectares, coordinates, address } = args

  const coordStr =
    coordinates
      ? `${formatCoordinates(coordinates.lat, coordinates.lng)} (${coordinates.lat.toFixed(6)}, ${coordinates.lng.toFixed(6)})`
      : "Not available"

  const locationStr = address?.formatted ?? "Not available"
  const areaStr = hectares && hectares > 0 ? `${hectares.toFixed(2)} ha` : "Not drawn"
  const corners = polygon ? polygon.geometry.coordinates[0].length - 1 : 0

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>Field Location Report – ${farmName ?? "FieldShift"}</title>
  <style>
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body { font-family: system-ui, sans-serif; color: #1E241B; padding: 40px; max-width: 700px; margin: auto; }
    h1 { font-size: 22px; font-weight: 800; margin-bottom: 4px; }
    .sub { font-size: 12px; color: #666; margin-bottom: 24px; }
    table { width: 100%; border-collapse: collapse; font-size: 13px; }
    td { padding: 8px 10px; border-bottom: 1px solid #e5e5e5; }
    td:first-child { color: #666; width: 160px; }
    td:last-child { font-weight: 600; }
    .footer { margin-top: 32px; font-size: 11px; color: #999; border-top: 1px solid #e5e5e5; padding-top: 12px; }
  </style>
</head>
<body>
  <h1>Field Location Report</h1>
  <p class="sub">Generated ${new Date().toLocaleString()} · FieldShift</p>
  <table>
    <tr><td>Farm name</td><td>${farmName ?? "—"}</td></tr>
    <tr><td>Field area</td><td>${areaStr}${corners > 0 ? ` · ${corners} corners` : ""}</td></tr>
    <tr><td>GPS centroid</td><td style="font-family:monospace">${coordStr}</td></tr>
    <tr><td>Location</td><td>${locationStr}</td></tr>
  </table>
  <div class="footer">
    This document is generated by FieldShift. Coordinates are approximate field centroid values derived from the drawn boundary.
  </div>
  <script>window.onload = () => window.print()</script>
</body>
</html>`

  const win = window.open("", "_blank")
  if (!win) return false
  win.document.write(html)
  win.document.close()
  return true
}
